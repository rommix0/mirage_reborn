# Builds app/resources/mirage_wordmark.svg: "Mirage" set in an instance of the Anybody
# variable font (SIL OFL 1.1; get Anybody[wdth,wght].ttf from github.com/google/fonts,
# ofl/anybody). Needs fontTools (pip install fonttools).
# usage: make_wordmark.py <Anybody[wdth,wght].ttf> <out.svg> [wdth=128] [wght=760] [tracking=-60]
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

src, out = sys.argv[1], sys.argv[2]
wdth = float(sys.argv[3]) if len(sys.argv) > 3 else 128
wght = float(sys.argv[4]) if len(sys.argv) > 4 else 760
track = float(sys.argv[5]) if len(sys.argv) > 5 else -60
font = TTFont(src)
print("axes", [(a.axisTag, a.minValue, a.maxValue) for a in font["fvar"].axes])
inst = instantiateVariableFont(font, {"wdth": wdth, "wght": wght})
gs = inst.getGlyphSet()
cmap = inst.getBestCmap()
hmtx = inst["hmtx"]

# Pair kerning from GPOS (format 1 and class-based format 2), first PairPos lookups only.
def kern(left, right):
    total = 0
    gpos = inst.get("GPOS")
    if not gpos: return 0
    for li in gpos.table.FeatureList.FeatureRecord:
        if li.FeatureTag != "kern": continue
        for idx in li.Feature.LookupListIndex:
            lk = gpos.table.LookupList.Lookup[idx]
            for st in lk.SubTable:
                if lk.LookupType == 9: st = st.ExtSubTable
                if getattr(st, "LookupType", lk.LookupType) != 2 and lk.LookupType not in (2, 9): continue
                if not hasattr(st, "Format") or left not in st.Coverage.glyphs: continue
                if st.Format == 1:
                    i = st.Coverage.glyphs.index(left)
                    for pvr in st.PairSet[i].PairValueRecord:
                        if pvr.SecondGlyph == right and pvr.Value1 and getattr(pvr.Value1, "XAdvance", 0):
                            return pvr.Value1.XAdvance
                elif st.Format == 2:
                    c1 = st.ClassDef1.classDefs.get(left, 0); c2 = st.ClassDef2.classDefs.get(right, 0)
                    v = st.Class1Record[c1].Class2Record[c2].Value1
                    if v and getattr(v, "XAdvance", 0): return v.XAdvance
    return total

text = "Mirage"
names = [cmap[ord(c)] for c in text]
paths, x = [], 0.0
bp = BoundsPen(gs)
for i, n in enumerate(names):
    pen = SVGPathPen(gs)
    gs[n].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))  # y up -> y down
    paths.append(pen.getCommands())
    gs[n].draw(TransformPen(bp, (1, 0, 0, 1, x, 0)))
    x += hmtx[n][0] + track
    if i + 1 < len(names): x += kern(n, names[i + 1])
xmin, ymin, xmax, ymax = bp.bounds
w, h = xmax - xmin, ymax - ymin
os2 = inst["OS/2"]
print(f"bounds x {xmin:.0f}..{xmax:.0f} y {ymin:.0f}..{ymax:.0f}  capH {os2.sCapHeight} upm {inst['head'].unitsPerEm}")
# viewBox in y-down coordinates; baseline is at y = 0, so the box is ymax above to -ymin below.
with open(out, "w", newline="\n") as f:
    f.write('<?xml version="1.0" encoding="UTF-8"?>\n')
    f.write(f'<!-- "Mirage" set in Anybody (SIL OFL 1.1, see fonts/OFL-Anybody.txt; tools/fonts/make_wordmark.py) at wdth {wdth:g}, wght {wght:g}, '
            f'tracking {track:g}; baseline at y=0. Generated by a fontTools script. -->\n')
    f.write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{xmin:.0f} {-ymax:.0f} {w:.0f} {h:.0f}">\n')
    f.write('  <path fill="#000000" d="' + " ".join(paths) + '"/>\n</svg>\n')
print("baseline fraction from top", round(ymax / h, 3), "aspect", round(w / h, 3))
